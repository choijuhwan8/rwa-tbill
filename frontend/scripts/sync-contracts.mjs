// Regenerates the frontend's view of the contracts from Foundry output:
//   - src/lib/abis.ts             typed ABIs (`as const`, so viem/wagmi infer arg + return types)
//   - src/deployments/index.ts    every <chainId>.json written by script/Deploy.s.sol
//
// Run after `forge build` or after a deploy:  npm run sync
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const frontend = join(here, "..");
const out = join(frontend, "..", "out");

const CONTRACTS = ["MockUSDC", "Whitelist", "TBillToken", "Vault"];

const abis = CONTRACTS.map((name) => {
  const artifact = JSON.parse(readFileSync(join(out, `${name}.sol`, `${name}.json`), "utf8"));
  const exportName = name[0].toLowerCase() + name.slice(1) + "Abi";
  return `export const ${exportName} = ${JSON.stringify(artifact.abi, null, 2)} as const;\n`;
});
writeFileSync(
  join(frontend, "src", "lib", "abis.ts"),
  `// AUTO-GENERATED by scripts/sync-contracts.mjs — do not edit by hand.\n\n${abis.join("\n")}`,
);

const deploymentsDir = join(frontend, "src", "deployments");
const chainIds = readdirSync(deploymentsDir)
  .filter((f) => /^\d+\.json$/.test(f))
  .map((f) => f.replace(".json", ""))
  .sort();
const imports = chainIds.map((id) => `import d${id} from "./${id}.json";`).join("\n");
const entries = chainIds.map((id) => `  ${id}: d${id} as Deployment,`).join("\n");
writeFileSync(
  join(deploymentsDir, "index.ts"),
  `// AUTO-GENERATED by scripts/sync-contracts.mjs — do not edit by hand.
import type { Address } from "viem";
${imports}

export type Deployment = {
  chainId: number;
  deployedAtBlock: number;
  usdc: Address;
  whitelist: Address;
  token: Address;
  vault: Address;
};

export const deployments: Record<number, Deployment> = {
${entries}
};
`,
);

console.log(`Synced ABIs for ${CONTRACTS.join(", ")}; deployments for chains [${chainIds.join(", ")}]`);
